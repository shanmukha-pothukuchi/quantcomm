/**
 * Sortable table.
 * @param {object[]} rows
 * @param {{key:string,label:string,fmt?:(v:any,r:object)=>string,num?:boolean}[]} cols
 * @param {{maxHeight?:number, empty?:string}} [opts]
 */
export function table(rows, cols, opts = {}) {
  const wrap = h("div.table-wrap", { style: opts.maxHeight ? { maxHeight: `${opts.maxHeight}px` } : null });
  if (!rows || !rows.length) {
    wrap.append(h("p.empty", opts.empty || "No rows."));
    return wrap;
  }
  let sortKey = null;
  let asc = true;
  const tbody = h("tbody");
  const draw = () => {
    const data = sortKey === null ? rows : [...rows].sort((a, b) => {
      const x = a[sortKey], y = b[sortKey];
      if (x === y) return 0;
      if (x === null || x === undefined) return 1;
      if (y === null || y === undefined) return -1;
      return (x > y ? 1 : -1) * (asc ? 1 : -1);
    });
    tbody.replaceChildren(...data.map((r) => h("tr", cols.map((c) =>
      h(c.num ? "td.num" : "td", c.fmt ? c.fmt(r[c.key], r) : r[c.key] ?? "—")))));
  };
  const head = h("tr", cols.map((c) => h(c.num ? "th.num" : "th",
    h("button", { type: "button", onclick: () => { asc = sortKey === c.key ? !asc : !c.num; sortKey = c.key; draw(); } }, c.label))));
  wrap.append(h("table", h("thead", head), tbody));
  draw();
  return wrap;
}

/**
 * Horizontal bar chart in HTML (accessible, no library).
 * @param {{label:string, value:number, display?:string, tone?:string}[]} items
 */
export function hbars(items, { title, max } = {}) {
  const top = max ?? Math.max(0, ...items.map((i) => (isNum(i.value) ? Math.abs(i.value) : 0)));
  return h("figure.barlist",
    title ? h("figcaption", title) : null,
    h("ul", items.map((i) => h("li",
      h("span.hb-label", { title: i.label }, i.label),
      h("span.hb-track", h(`i${i.tone ? `.tone-${i.tone}` : ""}`, { style: { width: `${top > 0 && isNum(i.value) ? Math.max(0.6, (Math.abs(i.value) / top) * 100) : 0}%` } })),
      h("b.hb-value", i.display ?? fmt.num(i.value))))));
}

/** Scatter plot in SVG. points: {x, y, group, tip} */
export function scatter(points, { xLabel, yLabel, yFmt = (v) => v.toFixed(2), groups = [] } = {}) {
  const W = 720, H = 340, M = { l: 58, r: 16, t: 14, b: 42 };
  const xs = points.map((p) => p.x), ys = points.map((p) => p.y);
  const pad = (lo, hi) => (lo === hi ? [lo - 1, hi + 1] : [lo - (hi - lo) * 0.05, hi + (hi - lo) * 0.05]);
  const [x0, x1] = pad(Math.min(0, ...xs), Math.max(...xs));
  const [y0, y1] = pad(Math.min(...ys), Math.max(...ys));
  const sx = (v) => M.l + ((v - x0) / (x1 - x0)) * (W - M.l - M.r);
  const sy = (v) => H - M.b - ((v - y0) / (y1 - y0)) * (H - M.t - M.b);
  const NS = "http://www.w3.org/2000/svg";
  const svg = document.createElementNS(NS, "svg");
  svg.setAttribute("viewBox", `0 0 ${W} ${H}`);
  svg.setAttribute("class", "scatter");
  svg.setAttribute("role", "img");
  svg.setAttribute("aria-label", `${yLabel} against ${xLabel}, ${points.length} points`);
  const add = (tag, attrs, text) => {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, v);
    if (text !== undefined) el.textContent = text;
    svg.append(el);
    return el;
  };
  for (let i = 0; i <= 4; i++) {
    const yv = y0 + ((y1 - y0) * i) / 4;
    add("line", { x1: M.l, x2: W - M.r, y1: sy(yv), y2: sy(yv), class: "grid" });
    add("text", { x: M.l - 8, y: sy(yv) + 4, class: "tick", "text-anchor": "end" }, yFmt(yv));
    const xv = x0 + ((x1 - x0) * i) / 4;
    add("text", { x: sx(xv), y: H - M.b + 16, class: "tick", "text-anchor": "middle" }, xv.toFixed(2));
  }
  if (y0 < 0 && y1 > 0) add("line", { x1: M.l, x2: W - M.r, y1: sy(0), y2: sy(0), class: "zero" });
  add("text", { x: (M.l + W - M.r) / 2, y: H - 6, class: "axis", "text-anchor": "middle" }, xLabel);
  add("text", { x: 14, y: (M.t + H - M.b) / 2, class: "axis", "text-anchor": "middle", transform: `rotate(-90 14 ${(M.t + H - M.b) / 2})` }, yLabel);
  for (const p of points) {
    const gi = Math.max(0, groups.indexOf(p.group));
    const c = add("circle", { cx: sx(p.x), cy: sy(p.y), r: 4.5, class: `pt g${gi % 8}` });
    const t = document.createElementNS(NS, "title");
    t.textContent = p.tip;
    c.append(t);
  }
  const legend = groups.length > 1 ? h("div.legend", groups.map((g, i) => h("span", h(`i.g${i % 8}`), g))) : null;
  return h("figure.scatter-wrap", svg, legend);
}

/** Render a tab body: shows a spinner, then the builder's nodes or a readable error. */
export async function mount(el, build) {
  el.replaceChildren(h("div.loading", h("span.spinner"), "Loading pipeline outputs…"));
  try {
    const nodes = await build();
    if (nodes === null) return; // superseded by a newer render
    el.replaceChildren(...[nodes].flat().filter(Boolean));
  } catch (err) {
    el.replaceChildren(note("error", h("b", "Couldn't load this view. "), err instanceof Error ? err.message : String(err)));
  }
}
