// Shared helpers for the dashboard: API access, formatting and small DOM components.
// Every value shown comes from /api/*; missing pipeline outputs render a "not generated yet" notice.

/** @param {string} path @returns {Promise<any>} data payload or throws Error(message) */
export async function api(path) {
  let res;
  try {
    res = await fetch(path, { headers: { Accept: "application/json" } });
  } catch (err) {
    throw new Error("Can't reach the FloodAlpha server. Is it running?");
  }
  let body = null;
  try { body = await res.json(); } catch (_) { /* non-JSON error page */ }
  if (!res.ok || !body || body.success !== true) {
    throw new Error((body && body.error) || `Request failed (${res.status})`);
  }
  return body.data;
}

// ------------------------------------------------------------ formatting --
const NUM = new Intl.NumberFormat("en-US");
export const isNum = (v) => typeof v === "number" && Number.isFinite(v);
export const fmt = {
  int: (v) => (isNum(v) ? NUM.format(Math.round(v)) : "—"),
  num: (v, d = 1) => (isNum(v) ? v.toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d }) : "—"),
  pct: (v, d = 1) => (isNum(v) ? `${fmt.num(v, d)} %` : "—"),
  frac: (v, d = 1) => (isNum(v) ? `${fmt.num(v * 100, d)} %` : "—"),
  usd: (v) => (isNum(v) ? `$${NUM.format(Math.round(v))}` : "—"),
  bnFromK: (v, d = 1) => (isNum(v) ? `$${fmt.num(v / 1e6, d)} bn` : "—"),
  mFromK: (v) => (isNum(v) ? `$${fmt.num(v / 1e3, 1)} M` : "—"),
  sci: (v) => (isNum(v) ? v.toExponential(2) : "—"),
  dt: (s, tz = true) => {
    if (!s) return "—";
    const d = new Date(s);
    if (Number.isNaN(d.getTime())) return String(s);
    const iso = d.toISOString().slice(0, 16).replace("T", " ");
    return tz ? `${iso} UTC` : iso;
  },
  bool: (v) => (v === true ? "yes" : v === false ? "no" : "—"),
};

